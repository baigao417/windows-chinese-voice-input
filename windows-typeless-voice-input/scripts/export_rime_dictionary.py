from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
PROJECT_ROOT = ROOT.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from win_voice_input.app import load_config, load_dictionary_entries  # noqa: E402


DEFAULT_OUTPUT_DIR = ROOT / "logs" / "rime-export"
DICT_FILENAME = "voice_input_typeless.dict.yaml"
CUSTOM_PHRASE_FILENAME = "voice_input_custom_phrase.txt"
SUMMARY_FILENAME = "rime-export-summary.json"


def normalize_code(value: str) -> str:
    value = value.strip().lower()
    if not value:
        return ""
    if not value.isascii():
        return ""
    value = re.sub(r"[^a-z0-9']+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def clean_field(value: Any) -> str:
    return str(value or "").replace("\t", " ").replace("\r", " ").replace("\n", " ").strip()


def code_for_entry(entry: dict[str, Any]) -> tuple[str, str]:
    aliases = entry.get("aliases")
    if isinstance(aliases, list):
        for alias in aliases:
            code = normalize_code(str(alias))
            if code:
                return code, "alias"
    code = normalize_code(str(entry.get("pronunciation") or ""))
    if code:
        return code, "pronunciation"
    code = normalize_code(str(entry.get("phrase") or ""))
    if code:
        return code, "phrase"
    return "", "none"


def read_input_entries(input_path: Path | None, config_path: str | None) -> list[dict[str, Any]]:
    if input_path is None:
        cfg = load_config(config_path)
        return load_dictionary_entries(cfg)
    cfg = load_config(config_path)
    cfg["dictionary_paths"] = [str(input_path)]
    cfg["dictionary_path"] = str(input_path)
    return load_dictionary_entries(cfg)


def rime_user_dir() -> Path:
    appdata = os.environ.get("APPDATA")
    if appdata:
        return Path(appdata) / "Rime"
    return Path.home() / "AppData" / "Roaming" / "Rime"


def render_dict_yaml(
    rows: list[dict[str, Any]],
    *,
    name: str,
    weight: int,
) -> str:
    today = time.strftime("%Y.%m.%d")
    lines = [
        "# Rime dictionary generated by Windows Typeless Voice Input.",
        "# Hook this file from a schema dictionary manually; this script does not edit Rime schemas.",
        "# encoding: utf-8",
        "---",
        f"name: {name}",
        f'version: "{today}"',
        "sort: by_weight",
        "...",
        "",
    ]
    for row in rows:
        lines.append(f"{row['phrase']}\t{row['code']}\t{weight}")
    return "\n".join(lines) + "\n"


def render_custom_phrase(rows: list[dict[str, Any]], *, weight: int) -> str:
    lines = [
        "# Rime custom phrase export generated by Windows Typeless Voice Input.",
        "# Format: phrase<TAB>code<TAB>weight",
        "# Import manually from your schema/custom-phrase setup; this script does not edit schemas.",
        "",
    ]
    for row in rows:
        lines.append(f"{row['phrase']}\t{row['code']}\t{weight}")
    return "\n".join(lines) + "\n"


def export_entries(
    entries: list[dict[str, Any]],
    *,
    output_dir: Path,
    include_no_code: bool,
    weight: int,
    formats: set[str],
) -> dict[str, Any]:
    exported: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []
    for entry in entries:
        phrase = clean_field(entry.get("phrase"))
        if not phrase:
            continue
        code, source = code_for_entry(entry)
        if not code and not include_no_code:
            skipped.append({"phrase": phrase, "reason": "no_ascii_alias_or_pronunciation"})
            continue
        exported.append(
            {
                "phrase": phrase,
                "code": code,
                "code_source": source,
                "aliases": entry.get("aliases") or [],
                "pronunciation": clean_field(entry.get("pronunciation")),
            }
        )

    output_dir.mkdir(parents=True, exist_ok=True)
    files: dict[str, str] = {}
    if "dict-yaml" in formats:
        path = output_dir / DICT_FILENAME
        path.write_text(
            render_dict_yaml(exported, name="voice_input_typeless", weight=weight),
            encoding="utf-8",
        )
        files["dict_yaml"] = str(path)
    if "custom-phrase" in formats:
        path = output_dir / CUSTOM_PHRASE_FILENAME
        path.write_text(render_custom_phrase(exported, weight=weight), encoding="utf-8")
        files["custom_phrase"] = str(path)

    summary = {
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "source_entries": len(entries),
        "exported_entries": len(exported),
        "skipped_entries": len(skipped),
        "include_no_code": include_no_code,
        "files": files,
        "code_source_counts": {
            source: sum(1 for row in exported if row["code_source"] == source)
            for source in sorted({row["code_source"] for row in exported})
        },
        "skipped": skipped[:50],
    }
    summary_path = output_dir / SUMMARY_FILENAME
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    summary["files"]["summary"] = str(summary_path)
    return summary


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Export Typeless-like dictionary entries to Rime files")
    parser.add_argument("--config", help="Optional voice-input config path")
    parser.add_argument("--input", type=Path, help="Optional dictionary input path; defaults to configured dictionary paths")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--apply-to-rime",
        action="store_true",
        help="Write to %%APPDATA%%\\Rime instead of the ignored demo logs export directory",
    )
    parser.add_argument(
        "--format",
        choices=["both", "dict-yaml", "custom-phrase"],
        default="both",
        help="Which Rime file format to write",
    )
    parser.add_argument("--include-no-code", action="store_true", help="Export entries without an ASCII code")
    parser.add_argument("--weight", type=int, default=1000)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    output_dir = rime_user_dir() if args.apply_to_rime else args.output_dir
    selected_formats = {"dict-yaml", "custom-phrase"} if args.format == "both" else {args.format}
    entries = read_input_entries(args.input, args.config)
    summary = export_entries(
        entries,
        output_dir=output_dir,
        include_no_code=args.include_no_code,
        weight=args.weight,
        formats=selected_formats,
    )
    print(
        "Exported {exported_entries}/{source_entries} entries; skipped={skipped_entries}; output={output}".format(
            **summary,
            output=output_dir,
        )
    )
    for label, path in summary["files"].items():
        print(f"{label}: {path}")
    if args.apply_to_rime:
        print("Wrote to Rime user dir. Open Weasel Deployer and redeploy after wiring these files into your schema.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
